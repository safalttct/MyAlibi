import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const envPath = resolve(root, '.env');
const outPath = resolve(root, 'src/environments/environment.generated.ts');

function loadDotEnv(filePath) {
  if (!existsSync(filePath)) {
    return {};
  }

  const values = {};
  for (const line of readFileSync(filePath, 'utf8').split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) {
      continue;
    }
    const eq = trimmed.indexOf('=');
    if (eq === -1) {
      continue;
    }
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    values[key] = value;
  }
  return values;
}

function firstDefined(...values) {
  for (const value of values) {
    if (typeof value === 'string' && value.trim()) {
      return value.trim();
    }
  }
  return '';
}

const fileEnv = loadDotEnv(envPath);

// Prefer NG_APP_* (app convention), then common Vercel/Supabase integration names.
const supabaseUrl = firstDefined(
  process.env.NG_APP_SUPABASE_URL,
  process.env.SUPABASE_URL,
  process.env.NEXT_PUBLIC_SUPABASE_URL,
  process.env.VITE_SUPABASE_URL,
  fileEnv.NG_APP_SUPABASE_URL,
  fileEnv.SUPABASE_URL,
);

const supabasePublishableKey = firstDefined(
  process.env.NG_APP_SUPABASE_PUBLISHABLE_KEY,
  process.env.SUPABASE_PUBLISHABLE_KEY,
  process.env.SUPABASE_ANON_KEY,
  process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY,
  process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY,
  process.env.VITE_SUPABASE_PUBLISHABLE_KEY,
  process.env.VITE_SUPABASE_ANON_KEY,
  fileEnv.NG_APP_SUPABASE_PUBLISHABLE_KEY,
  fileEnv.SUPABASE_PUBLISHABLE_KEY,
  fileEnv.SUPABASE_ANON_KEY,
);

const configured = Boolean(supabaseUrl && supabasePublishableKey);
const isProduction =
  process.env.NODE_ENV === 'production' || process.env.VERCEL === '1';

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(
  outPath,
  `// Generated by scripts/set-env.mjs — do not edit.
export const environment = {
  production: ${isProduction},
  supabaseUrl: ${JSON.stringify(supabaseUrl)},
  supabasePublishableKey: ${JSON.stringify(supabasePublishableKey)},
  configured: ${configured},
};
`,
  'utf8',
);

console.log(
  configured
    ? 'Environment generated with Supabase credentials.'
    : 'Environment generated without Supabase credentials (dev mode).',
);
