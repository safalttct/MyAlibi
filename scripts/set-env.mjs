import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const envPath = resolve(root, '.env');
const outPath = resolve(root, 'src/environments/environment.generated.ts');

function loadDotEnv(filePath) {
  if (!existsSync(filePath)) {
    return {};
  }

  const values = {};
  for (const line of readFileSync(filePath, 'utf8').split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) {
      continue;
    }
    const eq = trimmed.indexOf('=');
    if (eq === -1) {
      continue;
    }
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    values[key] = value;
  }
  return values;
}

const fileEnv = loadDotEnv(envPath);
const supabaseUrl =
  process.env.NG_APP_SUPABASE_URL || fileEnv.NG_APP_SUPABASE_URL || '';
const supabasePublishableKey =
  process.env.NG_APP_SUPABASE_PUBLISHABLE_KEY ||
  fileEnv.NG_APP_SUPABASE_PUBLISHABLE_KEY ||
  '';

const configured = Boolean(supabaseUrl && supabasePublishableKey);

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(
  outPath,
  `// Generated by scripts/set-env.mjs — do not edit.
export const environment = {
  production: ${process.env.NODE_ENV === 'production'},
  supabaseUrl: ${JSON.stringify(supabaseUrl)},
  supabasePublishableKey: ${JSON.stringify(supabasePublishableKey)},
  configured: ${configured},
};
`,
  'utf8',
);

console.log(
  configured
    ? 'Environment generated with Supabase credentials.'
    : 'Environment generated without Supabase credentials (dev mode).',
);
